#!/usr/bin/env node
// Copies this package into a repo's .claude/ and records what it copied.
//
//   node sync.mjs <repo> [--prefix ezaa] [--dry] [--check] [--init]
//
//   (no flag)  copy the shared scripts, tests and hook, regenerate both SKILL.md files, write
//              .claude/workflow.lock.json. Files the repo owns are never touched (below).
//   --dry      say what would change; write nothing.
//   --check    exit 1 when a shared file in the repo differs from the lock (someone edited the
//              copy instead of this package) or from this package (the repo is behind).
//   --init     a repo that has no config yet: write config.mjs and the two SKILL.repo.md files
//              from templates/ (edit them, then sync again).
//   --design   also install the visual-redesign method (design/): <prefix>-visual-redesign with
//              its references and sweep scripts. With --init it also writes the repo-owned
//              pieces: SKILL.repo.md, scripts/layout.config.mjs and the two agents. Repos whose
//              config.mjs exports DESIGN = true get it on every sync.
//
// The repo owns: <prefix>-issues/config.mjs, <prefix>-issues/SKILL.repo.md,
// <prefix>-sprint/SKILL.repo.md, and with design: <prefix>-visual-redesign/SKILL.repo.md,
// <prefix>-visual-redesign/scripts/layout.config.mjs, .claude/agents/<prefix>-{today-capture,visual-qa}.md. Everything else this script writes is shared: change it HERE.
// The prefix is read from the repo's existing `<prefix>-issues` folder, or the lock, or --prefix.
//
// Pure Node, no packages: a sprint never depends on the network.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const flag = n => args.includes(`--${n}`);
const opt = n => { const i = args.indexOf(`--${n}`); return i >= 0 ? args[i + 1] : null; };
const target = args.find((a, i) => !a.startsWith('--') && args[i - 1] !== '--prefix');
if (!target) { console.log('usage: node sync.mjs <repo> [--prefix p] [--dry] [--check] [--init]'); process.exit(2); }
const REPO = resolve(target);
const CLAUDE = join(REPO, '.claude');
const dry = flag('dry') || flag('check');

const sha = s => createHash('sha256').update(s).digest('hex').slice(0, 16);
const read = p => readFileSync(p, 'utf8').replace(/\r\n/g, '\n');
const version = read(join(HERE, 'VERSION')).trim();
const commit = (() => {
  try {
    const rev = execFileSync('git', ['-C', HERE, 'rev-parse', '--short', 'HEAD'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
    const dirty = execFileSync('git', ['-C', HERE, 'status', '--porcelain'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
    return dirty ? `${rev}+dirty` : rev;
  } catch { return 'unknown'; }
})();

// ---- the prefix ----
let lock = null;
try { lock = JSON.parse(readFileSync(join(CLAUDE, 'workflow.lock.json'), 'utf8')); } catch { /* first sync */ }
const skillsDir = join(CLAUDE, 'skills');
const found = existsSync(skillsDir) ? readdirSync(skillsDir).filter(d => /-issues$/.test(d)).map(d => d.replace(/-issues$/, '')) : [];
const PREFIX = opt('prefix') || lock?.prefix || (found.length === 1 ? found[0] : null);
if (!PREFIX) { console.log('Which prefix? Pass --prefix <short name> (the skills become <prefix>-issues and <prefix>-sprint).'); process.exit(2); }
const ISSUES = join(skillsDir, `${PREFIX}-issues`);
const SPRINT = join(skillsDir, `${PREFIX}-sprint`);
const DESIGN = join(skillsDir, `${PREFIX}-visual-redesign`);

// ---- what gets written ----
/** @type {Map<string, string>} path (relative to the repo) -> content */
const out = new Map();
const put = (rel, text) => out.set(rel.replace(/\\/g, '/'), text);
const relOf = p => p.slice(REPO.length + 1).replace(/\\/g, '/');
const files = dir => readdirSync(join(HERE, 'package', dir)).filter(f => statSync(join(HERE, 'package', dir, f)).isFile());

for (const f of files('issues')) put(relOf(join(ISSUES, f)), read(join(HERE, 'package/issues', f)));
for (const f of files('sprint')) put(relOf(join(SPRINT, f)), read(join(HERE, 'package/sprint', f)));
for (const f of files('hooks')) put(relOf(join(CLAUDE, 'hooks', f)), read(join(HERE, 'package/hooks', f)));
for (const f of files('tests')) put(relOf(join(CLAUDE, 'tests', f)), read(join(HERE, 'package/tests', f)).replaceAll('__P__', PREFIX));
// Where the shared scripts find the repo's values: one re-export each.
put(relOf(join(SPRINT, 'repo.mjs')), `// Generated by claude-workflow sync: the sprint reads the repo's values from the issues folder.\nexport * from '../${PREFIX}-issues/config.mjs';\n`);
put(relOf(join(CLAUDE, 'hooks', 'repo.mjs')), `// Generated by claude-workflow sync: the guard reads the repo's names from the issues folder.\nexport * from '../skills/${PREFIX}-issues/config.mjs';\n`);

// ---- the repo-owned files ----
const owned = [
  [join(ISSUES, 'config.mjs'), 'templates/config.template.mjs'],
  [join(ISSUES, 'SKILL.repo.md'), 'templates/issues.repo.template.md'],
  [join(SPRINT, 'SKILL.repo.md'), 'templates/sprint.repo.template.md'],
];
const missing = owned.filter(([p]) => !existsSync(p));
if (missing.length && !flag('init')) {
  console.log(`This repo has no ${missing.map(([p]) => relOf(p)).join(', ')}. Run again with --init to write starting versions, or copy them from another repo.`);
  process.exit(2);
}
if (flag('init')) {
  for (const [p, tpl] of missing) put(relOf(p), read(join(HERE, tpl)).replaceAll('__P__', PREFIX));
}

// ---- the SKILL.md files: repo part around the shared body ----
let cfg = null;
const cfgPath = join(ISSUES, 'config.mjs');
if (existsSync(cfgPath)) cfg = await import(pathToFileURL(cfgPath).href + `?t=${Date.now()}`);
else if (out.has(relOf(cfgPath))) cfg = null; // --init in this run: render after the next sync
function render(kind, repoFile) {
  const repoRel = relOf(repoFile);
  const repoText = out.has(repoRel) ? out.get(repoRel) : existsSync(repoFile) ? read(repoFile) : null;
  if (repoText == null || !cfg) return null;
  const shared = read(join(HERE, 'skill-text', `${kind}.shared.md`));
  const [before, after = ''] = repoText.split('<!-- shared -->');
  const tokens = {
    REPO: cfg.REPO, PREFIX, NAME: cfg.NAME, PROJECT_URL: cfg.PROJECT_URL, NEEDS_LIVE_TEXT: cfg.NEEDS_LIVE_TEXT,
  };
  const fill = t => t.replace(/\{\{(\w+)\}\}/g, (m, k) => {
    if (tokens[k] == null) throw new Error(`config.mjs does not export ${k} (used by the shared ${kind} SKILL text)`);
    return tokens[k];
  });
  return fill(`${before.trimEnd()}\n\n<!-- Generated by claude-workflow ${version}: edit SKILL.repo.md (this repo) or the package's skill-text/ (shared), not this file. -->\n\n${shared.trim()}\n\n${after.trim()}\n`);
}
const issuesSkill = render('issues', join(ISSUES, 'SKILL.repo.md'));
const sprintSkill = render('sprint', join(SPRINT, 'SKILL.repo.md'));
if (issuesSkill) put(relOf(join(ISSUES, 'SKILL.md')), issuesSkill);
if (sprintSkill) put(relOf(join(SPRINT, 'SKILL.md')), sprintSkill);

// ---- the visual-redesign method (design/) ----
const designOn = flag('design') || cfg?.DESIGN === true || lock?.design === true;
const designOwned = [
  [join(DESIGN, 'SKILL.repo.md'), 'templates/design.repo.template.md'],
  [join(DESIGN, 'scripts', 'layout.config.mjs'), 'design/visual-redesign/scripts/layout.config.template.mjs'],
  [join(CLAUDE, 'agents', `${PREFIX}-today-capture.md`), 'design/agents/today-capture.template.md'],
  [join(CLAUDE, 'agents', `${PREFIX}-visual-qa.md`), 'design/agents/visual-qa.template.md'],
];
if (designOn) {
  const walk = (dir, base = dir) => readdirSync(dir).flatMap(f => (statSync(join(dir, f)).isDirectory() ? walk(join(dir, f), base) : [join(dir, f).slice(base.length + 1)]));
  const SRC = join(HERE, 'design', 'visual-redesign');
  for (const f of walk(join(SRC, 'references'))) put(relOf(join(DESIGN, 'references', f)), read(join(SRC, 'references', f)));
  for (const f of walk(join(SRC, 'scripts'))) {
    if (f === 'layout.config.mjs') continue;
    put(relOf(join(DESIGN, 'scripts', f)), (f.endsWith('.mjs') || f.endsWith('.cjs')) ? read(join(SRC, 'scripts', f)) : read(join(SRC, 'scripts', f)));
  }
  if (flag('init')) for (const [p, tpl] of designOwned) if (!existsSync(p)) put(relOf(p), read(join(HERE, tpl)).replaceAll('__P__', PREFIX));
  const repoPart = join(DESIGN, 'SKILL.repo.md');
  const have = out.has(relOf(repoPart)) ? out.get(relOf(repoPart)) : existsSync(repoPart) ? read(repoPart) : null;
  if (have && cfg) {
    const [before, after = ''] = have.split('<!-- shared -->');
    const sharedBody = read(join(HERE, 'design', 'visual-redesign', 'skill.shared.md'));
    put(relOf(join(DESIGN, 'SKILL.md')), `${before.trimEnd()}

<!-- Generated by claude-workflow ${version}: edit SKILL.repo.md (this repo) or the package's design/visual-redesign/skill.shared.md (shared), not this file. -->

${sharedBody.trim().replaceAll('{{NAME}}', cfg.NAME).replaceAll('{{PREFIX}}', PREFIX)}

${after.trim()}
`);
  } else if (!have) console.log(`design: no ${relOf(repoPart)} yet: run with --design --init to write the repo-owned files.`);
}
const ownedAll = [...owned, ...(designOn ? designOwned : [])];

// ---- compare with what is there, and write ----
const state = rel => { const p = join(REPO, rel); return existsSync(p) ? read(p) : null; };
const changes = [];
for (const [rel, text] of out) {
  const now = state(rel);
  if (now === text) continue;
  changes.push([now == null ? 'new' : 'changed', rel]);
  if (!dry) { mkdirSync(dirname(join(REPO, rel)), { recursive: true }); writeFileSync(join(REPO, rel), text); }
}
// A shared file edited in the repo since the last sync is overwritten: say so.
const hand = [];
if (lock) for (const [rel, h] of Object.entries(lock.files || {})) {
  const now = state(rel);
  if (now != null && sha(now) !== h) hand.push(rel);
}

const shared = Object.fromEntries([...out].filter(([rel]) => !ownedAll.some(([p]) => relOf(p) === rel)).map(([rel, t]) => [rel, sha(t)]));
const newLock = { version, commit, prefix: PREFIX, design: designOn, syncedAt: new Date().toISOString().slice(0, 10), files: shared };

if (flag('check')) {
  for (const rel of hand) console.log(`edited in this repo since the last sync: ${rel}`);
  for (const [what, rel] of changes) console.log(`${what === 'new' ? 'missing' : 'behind the package'}: ${rel}`);
  console.log(changes.length || hand.length ? 'not in sync' : `in sync with claude-workflow ${version}`);
  process.exit(changes.length || hand.length ? 1 : 0);
}
for (const rel of hand) if (changes.some(([, r]) => r === rel)) console.log(`note: ${rel} had been edited in this repo; the package's copy replaced it (change the package, not the copy)`);
for (const [what, rel] of changes) console.log(`${dry ? '[dry] ' : ''}${what}: ${rel}`);
if (!dry) { mkdirSync(CLAUDE, { recursive: true }); writeFileSync(join(CLAUDE, 'workflow.lock.json'), JSON.stringify(newLock, null, 2) + '\n'); }
console.log(changes.length ? `${dry ? 'would sync' : 'synced'} ${changes.length} file(s) to claude-workflow ${version} (${commit})` : `already at claude-workflow ${version}`);
if (flag('init') && missing.length) console.log('Edit the files just written, then run sync again to generate the SKILL.md files.');
